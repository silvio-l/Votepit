#!/usr/bin/env bash
#
# Votepit — native local development setup (macOS + Homebrew, no Docker).
#
# Idempotent. Creates only what is missing:
#   config/config.php    dev config (gitignored), generated keys and DB password
#   config/dev-seed.env  demo owner e-mail + password for the demo seed (gitignored)
# Then creates the local MySQL database and user votepit_dev (synced with the
# config), installs vendor/ if needed, runs the migrations and the DEV-ONLY
# demo seed. Secrets are never printed.
#
# Usage:
#   bin/dev-setup.sh            set up or top up (safe to re-run)
#   bin/dev-setup.sh --reset    drop and recreate the dev database, then migrate and seed
#
set -euo pipefail

CORE="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
PHP="${PHP:-/opt/homebrew/bin/php}"
MYSQL="${MYSQL:-mysql}"
DB_NAME=votepit_dev
DB_USER=votepit_dev
RESET=0

case "${1:-}" in
  "") ;;
  --reset) RESET=1 ;;
  *) echo "usage: bin/dev-setup.sh [--reset]" >&2; exit 2 ;;
esac

cd "$CORE"

if [ ! -f vendor/autoload.php ]; then
  composer install --no-interaction
fi

if [ ! -f config/config.php ]; then
  app_key=$("$PHP" -r 'echo bin2hex(random_bytes(32));')
  identity_key=$("$PHP" -r 'echo bin2hex(random_bytes(32));')
  db_pass=$("$PHP" -r 'echo bin2hex(random_bytes(24));')
  umask 077
  cat > config/config.php <<CONFIG
<?php

declare(strict_types=1);

/**
 * LOCAL DEV ONLY, generated by bin/dev-setup.sh. Gitignored (/config/config.php).
 * Never copy this file to staging or production.
 */

return [
    'env' => 'dev',
    'app_url' => 'http://localhost:5173',
    'app_key' => '${app_key}',
    'identity_server_key' => '${identity_key}',
    'magic_link_ttl' => 60 * 15,
    'db' => [
        'host'    => '127.0.0.1',
        'port'    => 3306,
        'name'    => '${DB_NAME}',
        'user'    => '${DB_USER}',
        'pass'    => '${db_pass}',
        'charset' => 'utf8mb4',
    ],
    'smtp' => [
        'host'       => '',
        'port'       => 587,
        'user'       => '',
        'pass'       => '',
        'encryption' => 'tls',
        'from_email' => 'noreply@votepit-dev.invalid',
        'from_name'  => 'Votepit (dev)',
    ],
    'admin_emails' => ['demo-owner@votepit-dev.invalid'],
    'oauth_providers' => [],
    'session_lifetime' => 60 * 60 * 24 * 30,
    'routing_mode' => 'self-host',
    'trust_cloudflare_ip' => false,
    // The SPA issues many requests per page view; the production default (300/min per IP) trips locally.
    'rate_limits' => [
        'global:ip' => ['limit' => 5000, 'window' => 60],
    ],
];
CONFIG
  echo "created config/config.php (gitignored)"
fi

if [ ! -f config/dev-seed.env ]; then
  owner_pass=$("$PHP" -r 'echo bin2hex(random_bytes(24));')
  umask 077
  printf 'OWNER_PASSWORD=%s\n' "$owner_pass" > config/dev-seed.env
  echo "created config/dev-seed.env (gitignored)"
fi
# The login e-mail sits next to the password so the demo sign-in needs one file only
# (must match Votepit\Dev\DemoSeeder::OWNER_EMAIL; older files get the line appended).
if ! grep -q '^OWNER_EMAIL=' config/dev-seed.env; then
  printf 'OWNER_EMAIL=%s\n' "demo-owner@votepit-dev.invalid" >> config/dev-seed.env
fi

db_pass=$("$PHP" -r '$c = require "config/config.php"; echo $c["db"]["pass"];')

{
  if [ "$RESET" = 1 ]; then
    echo "DROP DATABASE IF EXISTS \`${DB_NAME}\`;"
  fi
  cat <<SQL
CREATE DATABASE IF NOT EXISTS \`${DB_NAME}\` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
CREATE USER IF NOT EXISTS '${DB_USER}'@'localhost' IDENTIFIED BY '${db_pass}';
CREATE USER IF NOT EXISTS '${DB_USER}'@'127.0.0.1' IDENTIFIED BY '${db_pass}';
ALTER USER '${DB_USER}'@'localhost' IDENTIFIED BY '${db_pass}';
ALTER USER '${DB_USER}'@'127.0.0.1' IDENTIFIED BY '${db_pass}';
GRANT ALL PRIVILEGES ON \`${DB_NAME}\`.* TO '${DB_USER}'@'localhost';
GRANT ALL PRIVILEGES ON \`${DB_NAME}\`.* TO '${DB_USER}'@'127.0.0.1';
FLUSH PRIVILEGES;
SQL
} | "$MYSQL" -uroot

"$PHP" bin/migrate.php --yes
"$PHP" bin/dev-seed.php

echo
echo "Done. Start the backend:   bin/dev-server.sh"
echo "Start the SPA (2nd shell): pnpm -C core/app dev   (from the repository root)"

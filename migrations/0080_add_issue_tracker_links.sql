-- 0080_add_issue_tracker_links — Linear/GitHub issue links (competitor-parity
-- issue 19).
--
-- account_issue_trackers: at most one connection per (account, provider).
--   token_encrypted   : the customer's Linear API key / GitHub fine-grained
--                       PAT. A bearer secret for a third-party system, so it
--                       is stored ENCRYPTED at rest (EncryptionService, own
--                       key-separation context 'issue_tracker_token') and
--                       never returned to the client — token_hint is the
--                       non-secret display form ("…a1b2").
--   target            : non-secret target the issues are created in —
--                       GitHub "owner/repo", Linear team key ("ENG").
--   target_id         : provider-side id resolved at connect time (Linear
--                       team UUID; empty for GitHub).
--   webhook_id        : random, public path segment of the inbound status-
--                       sync webhook URL. It only routes a delivery to its
--                       connection; authenticity comes from the signature.
--   webhook_secret_encrypted : HMAC secret the provider signs deliveries
--                       with (GitHub: generated by Votepit; Linear: pasted
--                       from Linear). Encrypted ('issue_tracker_webhook');
--                       NULL = status sync not configured (webhook → 404).
--
-- idea_issue_links: one created issue per (idea, provider). account_id is
-- denormalized so an inbound webhook can only ever resolve links of the
-- connection's own account (UNIQUE account_id/provider/external_id).
-- No PII: ids, the issue key and the issue URL only.
CREATE TABLE IF NOT EXISTS account_issue_trackers (
    id                       BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    account_id               BIGINT UNSIGNED NOT NULL,
    provider                 VARCHAR(16) NOT NULL,
    token_encrypted          VARCHAR(1024) NOT NULL,
    token_hint               VARCHAR(32) NOT NULL,
    target                   VARCHAR(200) NOT NULL,
    target_id                VARCHAR(64) NOT NULL DEFAULT '',
    webhook_id               CHAR(32) NOT NULL,
    webhook_secret_encrypted VARCHAR(512) NULL DEFAULT NULL,
    created_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at               TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_account_issue_trackers_account_provider (account_id, provider),
    UNIQUE KEY uniq_account_issue_trackers_webhook (webhook_id),
    CONSTRAINT fk_account_issue_trackers_account FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE CASCADE
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS idea_issue_links (
    id           BIGINT UNSIGNED NOT NULL AUTO_INCREMENT PRIMARY KEY,
    account_id   BIGINT UNSIGNED NOT NULL,
    idea_id      BIGINT UNSIGNED NOT NULL,
    provider     VARCHAR(16) NOT NULL,
    external_id  VARCHAR(64) NOT NULL,
    external_key VARCHAR(64) NOT NULL,
    url          VARCHAR(512) NOT NULL,
    created_by   BIGINT UNSIGNED NULL DEFAULT NULL,
    created_at   TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    UNIQUE KEY uniq_idea_issue_links_idea_provider (idea_id, provider),
    UNIQUE KEY uniq_idea_issue_links_external (account_id, provider, external_id),
    CONSTRAINT fk_idea_issue_links_account FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE CASCADE,
    CONSTRAINT fk_idea_issue_links_idea FOREIGN KEY (idea_id) REFERENCES ideas (id) ON DELETE CASCADE,
    CONSTRAINT fk_idea_issue_links_creator FOREIGN KEY (created_by) REFERENCES users (id) ON DELETE SET NULL
) ENGINE = InnoDB DEFAULT CHARSET = utf8mb4 COLLATE = utf8mb4_unicode_ci;

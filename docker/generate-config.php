<?php

declare(strict_types=1);

/**
 * Votepit — Docker config generator.
 *
 * Renders config/config.php from environment variables at container start
 * (see docker/entrypoint.sh). Only runs when config/config.php does not
 * exist yet, so a self-hoster can always drop in their own hand-edited
 * config/config.php (bind-mounted or baked into a custom image) instead —
 * this script never overwrites one.
 *
 * This is a Docker-only convenience layer: the shared-hosting path
 * (documentation/installation.md) keeps configuring config/config.php by
 * hand from config/config.example.php, unchanged. Every key here maps
 * 1:1 onto that file — see it for the meaning of each value.
 */

function env_str(string $name, string $default = ''): string
{
    $value = getenv($name);

    return $value === false ? $default : $value;
}

function env_int(string $name, int $default): int
{
    $value = getenv($name);

    return $value === false || $value === '' ? $default : (int) $value;
}

function env_bool(string $name, bool $default): bool
{
    $value = getenv($name);
    if ($value === false || $value === '') {
        return $default;
    }

    return in_array(strtolower($value), ['1', 'true', 'yes', 'on'], true);
}

/** @return list<string> */
function env_list(string $name): array
{
    $value = getenv($name);
    if ($value === false || trim($value) === '') {
        return [];
    }

    return array_values(array_filter(array_map('trim', explode(',', $value)), static fn (string $v): bool => $v !== ''));
}

$appKey            = env_str('VOTEPIT_APP_KEY');

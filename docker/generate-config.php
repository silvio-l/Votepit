if ($appKey === '' || $identityServerKey === '') {
    fwrite(STDERR, "Votepit (docker): VOTEPIT_APP_KEY and VOTEPIT_IDENTITY_SERVER_KEY are required and must not be empty.\n");
    fwrite(STDERR, "Generate each with: php -r \"echo bin2hex(random_bytes(32));\"\n");
    exit(1);
}

